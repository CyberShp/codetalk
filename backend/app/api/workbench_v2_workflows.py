@router.post("/workflows/{workflow_id}/versions/{version_id}/nodes", status_code=201)
async def add_canvas_node(
    workflow_id: str, version_id: str, payload: dict[str, Any]
) -> dict[str, Any]:
    """Add one Phase 3 node and allocate every node-owned identifier server-side."""
    _require_v2()
    _require_mutable_workflow(workflow_id)
    version = _require_v3_mutable_draft(workflow_id, version_id)
    expected_revision = _expected_v3_revision(payload)
    _require_current_v3_revision(version, expected_revision)
    _reject_client_owned_identity_fields(payload)
    unknown = sorted(
        set(payload) - {"expected_revision", "kind", "label", "position", "config"}
    )
    if unknown:
        raise _canvas_error(
            "node_command_fields_invalid",
            f"Unsupported node fields: {', '.join(unknown)}",
        )
    kind = str(payload.get("kind") or "").strip()
    if executable_node_definition(kind) is None:
        raise _canvas_error("node_kind_not_executable", f"Node kind is unavailable: {kind}")
    config = payload.get("config") if isinstance(payload.get("config"), dict) else {}
    try:
        node = build_v3_node(
            kind,
            label=str(payload.get("label") or "").strip() or None,
            position=payload.get("position") if isinstance(payload.get("position"), dict) else None,
            config=config,
        )
    except (CanvasAuthoringError, ValueError) as exc:
        raise _canvas_error("client_technical_ids_forbidden" if "technical_ids" in str(exc) else "node_command_invalid", str(exc)) from exc
    graph = deepcopy(version.authoring_graph)
    graph["nodes"].append(node)
    draft = _persist_v3_canvas_command(
        version_id, expected_revision=expected_revision, authoring_graph=graph
    )
    return {"node": node, "draft": _workflow_version_payload(draft)}


@router.post("/workflows/{workflow_id}/versions/{version_id}/nodes/{node_id}/ports", status_code=201)
async def add_canvas_port(
    workflow_id: str, version_id: str, node_id: str, payload: dict[str, Any]
) -> dict[str, Any]:
    """Add a typed V3 port without allowing a client-selected port ID."""
    _require_v2()
    _require_mutable_workflow(workflow_id)
    version = _require_v3_mutable_draft(workflow_id, version_id)
    expected_revision = _expected_v3_revision(payload)
    _require_current_v3_revision(version, expected_revision)
    _reject_client_owned_identity_fields(payload)
    direction = str(payload.get("direction") or "").strip()
    if direction not in {"inputs", "outputs"}:
        raise _canvas_error("port_direction_invalid", "direction must be inputs or outputs")
    port_type = str(payload.get("type") or "").strip()
    if not port_type:
        raise _canvas_error("port_type_required", "type is required")
    graph = deepcopy(version.authoring_graph)
    node = next((item for item in graph.get("nodes") or [] if str(item.get("id") or "") == node_id), None)
    if not isinstance(node, dict):
        raise HTTPException(status_code=404, detail=f"Unknown workflow node: {node_id}")
    port = build_v3_port(
        label=str(payload.get("label") or port_type),
        port_type=port_type,
        required=bool(payload.get("required", False)),
        collection=bool(payload.get("collection", False)),
    )
    node.setdefault("ports", {}).setdefault(direction, []).append(port)
    draft = _persist_v3_canvas_command(
        version_id, expected_revision=expected_revision, authoring_graph=graph
    )
    return {"port": port, "draft": _workflow_version_payload(draft)}


@router.patch(
    "/workflows/{workflow_id}/versions/{version_id}/nodes/{node_id}/ports/{port_id}"
)
async def update_canvas_port(
    workflow_id: str,
    version_id: str,
    node_id: str,
    port_id: str,
    payload: dict[str, Any],
) -> dict[str, Any]:
    """Edit user-facing port properties without replacing its stable ID."""
    _require_v2()
    _require_mutable_workflow(workflow_id)
    version = _require_v3_mutable_draft(workflow_id, version_id)
    expected_revision = _expected_v3_revision(payload)
    _require_current_v3_revision(version, expected_revision)
    _reject_client_owned_identity_fields(payload)
    unknown = sorted(
        set(payload) - {"expected_revision", "label", "type", "required", "collection"}
    )
    if unknown:
        raise _canvas_error("port_update_fields_invalid", f"Unsupported port fields: {', '.join(unknown)}")
    graph = deepcopy(version.authoring_graph)
    port = _find_canvas_port(graph, node_id, port_id)
    if "label" in payload:
        label = str(payload["label"] or "").strip()
        if not label:
            raise _canvas_error("port_label_required", "Port label is required")
