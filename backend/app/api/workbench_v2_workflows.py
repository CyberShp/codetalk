async def compile_workflow_version(
    workflow_id: str,
    version_id: str,
    payload: WorkflowDerivedRequest | None = None,
) -> dict[str, Any]:
    _require_v2()
    _require_mutable_workflow(workflow_id)
    version = _version_for_workflow(workflow_id, version_id)
    if version.state != "draft":
        raise HTTPException(status_code=409, detail="Published workflow versions are immutable")
    expected_revision = _derived_expected_revision(
        version, payload.expected_revision if payload else None
    )
    try:
        compiled = compile_workflow_graph(
            version.authoring_graph,
            capabilities=_workflow_graph_capabilities(),
            workflow_version_id=version.version_id,
            workflow_version_number=version.version_number,
        )
    except WorkflowGraphValidationError as exc:
        raise HTTPException(
            status_code=422,
            detail=_with_draft_revision(exc.validation, version),
        )

    saved = _update_compiled_draft(
        version,
        expected_revision=expected_revision,
        compiled_definition=compiled["compiled_definition"],
        compiled_plan=compiled["compiled_plan"],
        validation=compiled["validation_result"],
    )
    return _with_draft_revision(compiled, saved)


@router.post("/workflows/{workflow_id}/versions/{version_id}/publish")
async def publish_workflow_version(
    workflow_id: str,
    version_id: str,
    payload: WorkflowPublishRequest,
) -> dict[str, Any]:
    _require_v2()
    _require_mutable_workflow(workflow_id)
    version = _version_for_workflow(workflow_id, version_id)
    expected_revision = _derived_expected_revision(
        version, payload.expected_revision
    )
    try:
        compiled = compile_workflow_graph(
            version.authoring_graph,
            capabilities=_workflow_graph_capabilities(),
            workflow_version_id=version.version_id,
            workflow_version_number=version.version_number,
        )
        version = workflow_version_store().publish_version(
            version_id,
            expected_revision=expected_revision,
            authoring_graph=version.authoring_graph,
            compiled_definition=compiled["compiled_definition"],
            compiled_plan=compiled["compiled_plan"],
            validation=compiled["validation_result"],
        )
    except WorkflowGraphValidationError as exc:
        raise HTTPException(
            status_code=422,
            detail=_with_draft_revision(exc.validation, version),
        )
    except StaleWorkflowDraftError as exc:
        raise _canvas_error("stale_draft", str(exc), status_code=409) from exc
    except PublishedWorkflowVersionError as exc:
        raise HTTPException(status_code=409, detail=str(exc))
    except (WorkflowVersionError, ValueError) as exc:
        raise HTTPException(status_code=422, detail=str(exc))
    return asdict(version)


@router.post(
    "/workflows/{workflow_id}/versions/{version_id}/test-run",
    status_code=201,
)
async def prepare_workflow_trial_run(
    workflow_id: str,
    version_id: str,
    payload: WorkflowTrialRunRequest,
) -> dict[str, Any]:
    """Compile a draft server-side and prepare a real, isolated run snapshot."""
    _require_v2()
    _require_mutable_workflow(workflow_id)
    version = _version_for_workflow(workflow_id, version_id)
    if version.state != "draft":
        raise HTTPException(status_code=409, detail="只能试运行工作流草稿")
    expected_revision = _derived_expected_revision(version, payload.expected_revision)
    workspace = _resolve_workspace(payload.workspace_id)
    repo_path = Path(str(workspace["repo_path"])).expanduser().resolve()
    if not repo_path.exists() or not repo_path.is_dir():
        raise HTTPException(
            status_code=422,
            detail=f"工作空间源码目录不可用：{repo_path}",
        )
    try:
        compiled = compile_workflow_graph(
            version.authoring_graph,
            capabilities=_workflow_graph_capabilities(),
            workflow_version_id=version.version_id,
            workflow_version_number=version.version_number,
        )
    except WorkflowGraphValidationError as exc:
        raise HTTPException(
            status_code=422,
            detail=_with_draft_revision(exc.validation, version),
        )

    if payload.node_id:
        try:
            compiled = _diagnostic_node_trial(compiled, payload.node_id)
        except ValueError as exc:
            raise HTTPException(status_code=422, detail=str(exc)) from exc

    resolved_inputs = dict(payload.inputs)
    for input_definition in compiled["compiled_definition"].get("inputs") or []:
        if str(input_definition.get("resolver") or "") == "workspace":
            resolved_inputs[str(input_definition["id"])] = str(repo_path)
    try:
        WorkbenchTaskRunPreparer.preflight_inputs(
            workflow_snapshot=compiled["compiled_definition"],
            inputs=resolved_inputs,
        )
    except (FileNotFoundError, ValueError) as exc:
        raise HTTPException(
            status_code=422,
            detail=f"工作流输入不完整或无效：{exc}",
        ) from exc

    saved = None
    if expected_revision is not None:
        saved = _update_compiled_draft(
            version,
            expected_revision=expected_revision,
            compiled_definition=compiled["compiled_definition"],
            compiled_plan=compiled["compiled_plan"],
            validation=compiled["validation_result"],
        )

    root = settings.data_path / "workbench"
    trial_workflow_store = WorkflowStore(root / "trial_workflows.db")
    trial_workflow_store.save_workflow(compiled["compiled_definition"])
    try:
        prepared = WorkbenchTaskRunPreparer(
            artifact_root=root / "task_runs",
            workflow_store=trial_workflow_store,
            evidence_memory=EvidenceMemoryStore(root / "evidence_memory.db"),
            semantic_library=TestSemanticLibraryStore(root / "test_semantics.db"),
        ).prepare(
            workflow_id=workflow_id,
            workspace_id=payload.workspace_id,
            repo_path=str(repo_path),
            inputs=resolved_inputs,
        )
    except (FileNotFoundError, ValueError) as exc:
        if saved is not None:
            raise HTTPException(
                status_code=500,
                detail=f"试运行提交后准备失败，请查看服务端诊断：{exc}",
            ) from exc
        raise HTTPException(
            status_code=422,
            detail=f"工作流输入不完整或无效：{exc}",
        ) from exc
    prepared.task_bundle["compiled_definition"] = compiled["compiled_definition"]
    prepared.task_bundle["compiled_plan"] = compiled["compiled_plan"]
    prepared.task_bundle["workflow_version_id"] = version.version_id
    prepared.task_bundle["trial_run"] = True
    prepared.task_bundle["diagnostic"] = {
        "kind": "node_trial" if payload.node_id else "workflow_trial",
        "node_id": payload.node_id or None,
        "not_a_formal_delivery": True,
    }
    task_run_file = Path(prepared.artifact_dir) / "task_run.json"
    task_run_file.write_text(
        json.dumps(asdict(prepared), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (Path(prepared.artifact_dir) / "task_bundle.json").write_text(
        json.dumps(prepared.task_bundle, ensure_ascii=False, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    refresh_run_snapshot_v3(prepared.artifact_dir)
    if saved is None:
        saved = _update_compiled_draft(
            version,
            compiled_definition=compiled["compiled_definition"],
            compiled_plan=compiled["compiled_plan"],
            validation=compiled["validation_result"],
        )
    return {
        "status": "prepared",
        "task_run_id": prepared.task_run_id,
        "workflow_id": workflow_id,
        "workflow_version_id": version_id,
        "workspace_id": payload.workspace_id,
        "compiled_plan": compiled["compiled_plan"],
        "draft_revision": saved.draft_revision,
        "diagnostic": prepared.task_bundle["diagnostic"],
    }


def _diagnostic_node_trial(compiled: dict[str, Any], node_id: str) -> dict[str, Any]:
    """Keep the public compiler contract, but execute exactly one executable node.

    This is intentionally derived from the compiled graph rather than from a
    separate trial DSL, so readiness, Harness, network policy and collection
    use the same task-run path as a normal execution.
    """
    plan = dict(compiled["compiled_plan"])
    selected = next(
        (item for item in plan.get("nodes") or [] if str(item.get("graph_node_id")) == node_id),
        None,
    )
    if not isinstance(selected, dict):
        raise ValueError("请选择一个可执行节点后再试运行")
    step_id = str(selected.get("node_id") or "")
    if not step_id:
        raise ValueError("所选节点缺少可执行步骤")
    definition = dict(compiled["compiled_definition"])
    definition["steps"] = [
        item for item in definition.get("steps") or []
        if isinstance(item, dict) and str(item.get("id") or "") == step_id
    ]
    if not definition["steps"]:
        raise ValueError("所选节点不是可试运行的执行节点")
    declared_input_ids = {
        str(item.get("id") or "")
        for item in definition.get("inputs") or []
        if isinstance(item, dict)
    }
    required_inputs: set[str] = set()
    for target_port, resolved in (selected.get("resolved_input_bindings") or {}).items():
        bindings = resolved if isinstance(resolved, list) else [resolved]
        found_source_input = False
        for binding in bindings:
            if not isinstance(binding, dict):
                continue
            source_input_id = str(binding.get("source_input_id") or "")
            if source_input_id:
                required_inputs.add(source_input_id)
                found_source_input = True
        if not found_source_input and str(target_port) in declared_input_ids:
            required_inputs.add(str(target_port))
    definition["inputs"] = [
        item for item in definition.get("inputs") or []
        if isinstance(item, dict) and str(item.get("id") or "") in required_inputs
    ]
    definition["outputs"] = [
        item for item in definition.get("outputs") or []
        if isinstance(item, dict) and str(item.get("from") or item.get("source") or "") == step_id
    ]
    plan["nodes"] = [{**selected, "depends_on": []}]
    plan["topological_order"] = [step_id]
    return {**compiled, "compiled_definition": definition, "compiled_plan": plan}


def _version_for_workflow(workflow_id: str, version_id: str):
    try:
        version = workflow_version_store().get_version(version_id)
    except KeyError:
        raise HTTPException(status_code=404, detail=f"Unknown workflow version: {version_id}")
    if version.workflow_id != workflow_id:
        raise HTTPException(status_code=404, detail=f"Unknown workflow version: {version_id}")
    return version


def _require_v3_mutable_draft(workflow_id: str, version_id: str):
    version = _version_for_workflow(workflow_id, version_id)
    if version.state != "draft":
        raise HTTPException(status_code=409, detail="Published workflow versions are immutable")
    if version.authoring_graph.get("schema_version") != 3:
        raise HTTPException(status_code=409, detail="Canvas commands require a V3 workflow draft")
    return version


def _assert_edge_ports_exist(
    graph: dict[str, Any],
    source: dict[str, Any],
    target: dict[str, Any],
    *,
    exclude_edge_id: str = "",
) -> None:
    nodes = {
        str(node.get("id") or ""): node
        for node in graph.get("nodes") or []
        if isinstance(node, dict)
    }
    source_id = str(source.get("node_id") or "")
    target_id = str(target.get("node_id") or "")
    source_port = str(source.get("port_id") or "")
    target_port = str(target.get("port_id") or "")
    source_node, target_node = nodes.get(source_id), nodes.get(target_id)
    if not source_node or not target_node:
        raise _canvas_error("edge_node_unknown", "Source and target nodes must exist")
    source_ports = {
        str(port.get("id") or ""): str(port.get("type") or "")
        for port in (source_node.get("ports") or {}).get("outputs") or []
        if isinstance(port, dict)
    }
    target_ports = {
        str(port.get("id") or ""): port
        for port in (target_node.get("ports") or {}).get("inputs") or []
        if isinstance(port, dict)
    }
    if source_port not in source_ports or target_port not in target_ports:
        raise _canvas_error("edge_port_unknown", "Source and target ports must exist")
    target_definition = target_ports[target_port]
    occupied = any(
        str(edge.get("kind") or "") == "data"
        and str(edge.get("id") or "") != exclude_edge_id
        and str((edge.get("target") or {}).get("node_id") or "") == target_id
        and str((edge.get("target") or {}).get("port_id") or "") == target_port
        for edge in graph.get("edges") or []
        if isinstance(edge, dict)
    )
    if occupied and not bool(target_definition.get("collection")):
        raise _canvas_error("multiple_edges_to_single_input", "该输入已绑定")
    target_type = str(target_definition.get("type") or "")
    if not _port_types_compatible(source_ports[source_port], target_type):
        raise _canvas_error(
            "port_type_mismatch",
            f"端口类型不兼容：{source_ports[source_port]} → {target_type}",
        )


def _port_types_compatible(source_type: str, target_type: str) -> bool:
    return source_type == target_type or source_type == "any" or target_type == "any"


def _find_canvas_port(
    graph: dict[str, Any], node_id: str, port_id: str
) -> dict[str, Any]:
    node = next(
        (item for item in graph.get("nodes") or [] if isinstance(item, dict) and str(item.get("id") or "") == node_id),
        None,
    )
    if node is None:
        raise HTTPException(status_code=404, detail=f"Unknown workflow node: {node_id}")
    ports = node.get("ports") if isinstance(node.get("ports"), dict) else {}
    for direction in ("inputs", "outputs"):
        for port in ports.get(direction) or []:
            if isinstance(port, dict) and str(port.get("id") or "") == port_id:
                return port
    raise HTTPException(status_code=404, detail=f"Unknown workflow port: {port_id}")


