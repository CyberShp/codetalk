@router.post("/workflows/new", status_code=201)
async def create_canvas_workflow(payload: dict[str, Any]) -> dict[str, Any]:
    """Create a Canvas First V3 draft without accepting client technical IDs."""
    _require_v2()
    _reject_client_owned_identity_fields(payload)
    unknown = sorted(set(payload) - {"template", "name", "description"})
    if unknown:
        raise _canvas_error("canvas_create_fields_invalid", f"Unsupported create fields: {', '.join(unknown)}")
    template = str(payload.get("template") or "").strip()
    if template not in CANVAS_TEMPLATES:
        raise _canvas_error("canvas_template_invalid", "template must be blank or free_source_analysis")
    name = str(payload.get("name") or "").strip()
    if not name:
        raise _canvas_error("workflow_name_required", "name is required")
    workflow_id = new_workflow_id()
    graph = build_canvas_graph(
        workflow_id=workflow_id,
        name=name,
        description=str(payload.get("description") or ""),
        template=template,
    )
    try:
        header, draft = workflow_version_store().create_canvas_workflow(
            workflow_id=workflow_id,
            name=name,
            description=str(payload.get("description") or ""),
            authoring_graph=graph,
        )
    except WorkflowVersionError as exc:
        raise _canvas_error("canvas_create_failed", str(exc)) from exc
    return {
        "workflow": asdict(header),
        "draft": _workflow_version_payload(draft),
        "designer_url": f"/workflows/{header.workflow_id}/designer",
        "meta": {"backend_commit_sha": _backend_commit_sha(), "schema_version": 3},
    }


